import fs from 'node:fs';

const paths = [
  'src/components/AdminPendaftaranTurnamenModern.tsx',
  'src/components/AdminPendaftaranTurnamenModernV2.tsx',
];

const helper = `\nconst ADMIN_REGISTRATION_API = '/api/admin-tournament';\nfunction getTournamentAdminPin() {\n  try {\n    const raw = localStorage.getItem('pb162_user_pins');\n    const dict = raw ? JSON.parse(raw) : {};\n    return String(dict?.admin?.pin || '');\n  } catch { return ''; }\n}\nasync function loadTournamentRegistrationsViaApi() {\n  const response = await fetch(ADMIN_REGISTRATION_API, {\n    method: 'GET',\n    headers: { 'x-admin-pin': getTournamentAdminPin() },\n    cache: 'no-store',\n  });\n  const payload = await response.json().catch(() => ({}));\n  if (!response.ok) throw new Error(payload?.error || 'Gagal memuat data pendaftaran.');\n  return payload?.data || [];\n}\n`;

for (const path of paths) {
  if (!fs.existsSync(path)) continue;
  let src = fs.readFileSync(path, 'utf8');
  if (!src.includes('loadTournamentRegistrationsViaApi')) {
    const marker = path.endsWith('V2.tsx')
      ? 'export default function AdminPendaftaranTurnamenModernV2() {'
      : 'export default function AdminPendaftaranTurnamenModern() {';
    if (src.includes(marker)) src = src.replace(marker, helper + '\n' + marker);
  }

  // Replace the direct Supabase GET generated by the direct-client patch.
  src = src.replace(/const \{ data, error \} = await supabase\.from\('pendaftaran_turnamen'\)\.select\('[^']+'\)\.order\('created_at', \{ ascending: false \}\)(?:\.range\(0, 999\))?;/g,
    `const data = await loadTournamentRegistrationsViaApi(); const error = null;`);

  // Also replace a wildcard direct GET if an older patch variant remains.
  src = src.replace(/const \{ data, error \} = await supabase\.from\('pendaftaran_turnamen'\)\.select\('\*'\)\.order\('created_at', \{ ascending: false \}\);/g,
    `const data = await loadTournamentRegistrationsViaApi(); const error = null;`);

  fs.writeFileSync(path, src, 'utf8');
  console.log(`[patch-admin-registration-api-fallback] ${path} patched`);
}
