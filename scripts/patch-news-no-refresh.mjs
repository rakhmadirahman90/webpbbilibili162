import fs from 'node:fs';
import path from 'node:path';

const file = path.resolve('src/components/News.tsx');
let source = fs.readFileSync(file, 'utf8');
let changes = 0;

function replaceOnce(oldText, newText, label, required = false) {
  if (!source.includes(oldText)) {
    if (required) throw new Error(`[news-no-refresh] Target not found: ${label}`);
    return;
  }
  source = source.replace(oldText, newText);
  changes++;
  console.log(`[news-no-refresh] ${label}`);
}

// Keep the article modal entirely local to News. URL synchronization was causing
// App's dedicated-view synchronizer to participate in opening/closing the modal.
const stage2 = /  \/\/ Stage 2: Reactively synchronize state changes with URL query parameters\n  useEffect\(\(\) => \{[\s\S]*?\n  \}, \[selectedNews, hasInitializedUrlNews, searchParams, setSearchParams\]\);/;
if (stage2.test(source)) {
  source = source.replace(stage2, `  // Article open/close is local UI state. Do not navigate or remount the page.\n  useEffect(() => {\n    if (!selectedNews && searchParams.get('newsId')) {\n      setSearchParams(prev => {\n        const next = new URLSearchParams(prev);\n        next.delete('newsId');\n        return next;\n      }, { replace: true });\n    }\n  }, [selectedNews, searchParams, setSearchParams]);`);
  changes++;
  console.log('[news-no-refresh] replaced reactive URL sync with close-only cleanup');
}

// Opening an article must never fall back to fetchNews(). A failed view counter
// update must not destroy the currently visible article or show a page loader.
const openStart = source.indexOf('  // Always open the canonical article row from Supabase, then persist the new view count.');
const openEnd = source.indexOf('\n\n  const handleSubmitComment', openStart);
if (openStart >= 0 && openEnd > openStart) {
  const replacement = `  // Open immediately from the already-loaded list. Persist the view count in the background\n  // so opening an article can never trigger a page reload/loading state.\n  const handleOpenNews = (news: Berita) => {\n    const nextViews = (Number(news.views) || 0) + 1;\n    const opened = { ...news, views: nextViews } as Berita;\n\n    setSelectedNews(opened);\n    setActiveImgIndex(0);\n    setComments([]);\n    void fetchComments(opened.id);\n\n    // Optimistic local update keeps the list stable while Supabase persists the view.\n    setBeritaList(prev => prev.map(item =>\n      item.id === opened.id ? { ...item, views: nextViews } : item\n    ));\n\n    void supabase\n      .from('berita')\n      .update({ views: nextViews })\n      .eq('id', opened.id)\n      .then(({ error }) => {\n        if (error) console.warn('[News] Gagal menyimpan views:', error.message);\n      });\n  };`;
  source = source.slice(0, openStart) + replacement + source.slice(openEnd);
  changes++;
  console.log('[news-no-refresh] replaced blocking article open with optimistic background view update');
}

// Realtime UPDATEs (especially the view counter generated by this client) must
// patch only the matching row. Never set loading and never replace the whole list.
replaceOnce(
`          setBeritaList(prev => prev.map(item => \n            item.id === updated.id \n              ? { \n                  ...item, \n                  ...updated,\n                  likes: Number(updated.likes) || 0, \n                  views: Number(updated.views) || 0\n                } \n              : item\n          ));`,
`          setBeritaList(prev => prev.map(item =>\n            item.id === updated.id\n              ? { ...item, ...updated, likes: Number(updated.likes) || 0, views: Number(updated.views) || 0 }\n              : item\n          ));`,
'realtime row-only update');

// Do not replace the open article object on a view-count-only realtime event.
// This avoids remount-like animation churn while the article is being read.
replaceOnce(
`          setSelectedNews(prev => prev?.id === updated.id ? { ...prev, ...updated, likes: Number(updated.likes) || 0, views: Number(updated.views) || 0 } : prev);`,
`          if (selectedNews?.id === updated.id) {\n            setSelectedNews(prev => prev ? { ...prev, ...updated, likes: Number(updated.likes) || 0, views: Number(updated.views) || 0 } : prev);\n          }`,
'selected article realtime update');

// The callback above intentionally reads the current selectedNews value only for
// deciding whether to patch it; use a ref so realtime does not depend on render state.
if (!source.includes("const selectedNewsRef")) {
  replaceOnce(
`  const [selectedNews, setSelectedNews] = useState<Berita | null>(null);`,
`  const [selectedNews, setSelectedNews] = useState<Berita | null>(null);\n  const selectedNewsRef = useRef<Berita | null>(null);`,
'add selected article ref');
  replaceOnce(
`import { useState, useEffect, useMemo } from 'react';`,
`import { useState, useEffect, useMemo, useRef } from 'react';`,
'add useRef import');
  replaceOnce(
`  // Dispatch overlay events to control App.tsx's unified control dock visibility`,
`  useEffect(() => {\n    selectedNewsRef.current = selectedNews;\n  }, [selectedNews]);\n\n  // Dispatch overlay events to control App.tsx's unified control dock visibility`,
'keep selected article ref current');
  replaceOnce(
`          if (selectedNews?.id === updated.id) {\n            setSelectedNews(prev => prev ? { ...prev, ...updated, likes: Number(updated.likes) || 0, views: Number(updated.views) || 0 } : prev);\n          }`,
`          if (selectedNewsRef.current?.id === updated.id) {\n            setSelectedNews(prev => prev ? { ...prev, ...updated, likes: Number(updated.likes) || 0, views: Number(updated.views) || 0 } : prev);\n          }`,
'use selected article ref in realtime');
}

if (changes === 0) {
  console.log('[news-no-refresh] already patched');
} else {
  fs.writeFileSync(file, source, 'utf8');
  console.log(`[news-no-refresh] applied ${changes} changes`);
}
